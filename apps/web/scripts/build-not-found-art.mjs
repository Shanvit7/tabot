import { writeFileSync } from "node:fs";
import * as A from "../../../.agents/skills/anatomy/kit/audit.mjs";
import * as k from "../../../.agents/skills/anatomy/kit/iso-kit.mjs";
import * as G from "../../../.agents/skills/anatomy/kit/lathe.mjs";

// Static Anatomy Figure: an oversized 404 wayfinder at the end of a short trail.
// Ground, inset surface, four feet and screws, flush trail inlay, sign foot,
// socket, pole, collar, layered plate, face inset, four plate screws.
const width = 600;
const height = 440;
const base = { x: -67, y: -47, w: 134, d: 94, r: 12 };
const points = [...k.boxCorners(base, -9, 0), [-1, 0, 95], [0, 0, 0]];
const projection = k.fitProjection(points, width, height, {
	pad: 54,
	azimuth: 40,
	elevation: 30,
});
const recorder = A.recorder(projection);
const parts = new Map();
const add = (
	name,
	at,
	paths,
	shape,
	material = "stone",
	tone = "mid",
	line = "",
) => {
	parts.set(name, { name, paths, material, tone, line, dots: [] });
	recorder.put({
		name,
		at,
		svg: k.solidSvg(paths, { tone, inner: k.lineSvg(line) }),
		shapes: [
			recorder.solid({ ...shape, name, ground: name.startsWith("foot.") }),
		],
	});
};
const slab = (name, plan, z, thickness, material, tone = "mid", line = "") =>
	add(
		name,
		[plan.x + plan.w / 2, plan.y + plan.d / 2, z + thickness / 2],
		k.slabOf(plan, z, thickness, projection, 8, Math.min(0.8, thickness / 4)),
		A.slab(plan, z, thickness),
		material,
		tone,
		line,
	);
const disc = (
	name,
	x,
	y,
	radius,
	z,
	thickness,
	material = "metal",
	tone = "mid",
) => {
	const frame = G.frameOf([x, y, 0], [0, 0, 1], [1, 0, 0], [0, 1, 0]);
	add(
		name,
		[x, y, z + thickness / 2],
		G.disc(z, z + thickness, radius, frame, projection),
		A.disc(frame, z, z + thickness, radius),
		material,
		tone,
	);
};
const prism = (name, frame, polygon, from, to, material, tone = "mid") =>
	add(
		name,
		frame.o,
		G.prismOf(frame, polygon, from, to, projection),
		A.prism(frame, polygon, from, to),
		material,
		tone,
	);

for (const [index, [x, y]] of k.corners(base, 15).entries())
	disc(`foot.${index}`, x, y, 4.5, -9, 3, "stone", "lo");
slab(
	"plinth",
	base,
	-6,
	5,
	"stone",
	"lo",
	k.sideSeam(base, -3.5, projection, 8),
);
const top = k.insetPlan(base, 2);
slab(
	"surface",
	top,
	-1,
	1,
	"paper",
	"lo",
	k.planOutline(k.insetPlan(top, 3), 0, projection),
);
for (const [index, [x, y]] of k.corners(base, 7).entries()) {
	const part = parts.get(`foot.${index}`);
	part.dots.push(k.iso([x, y, 0.4], projection));
}
// A pale path points directly at the sign, with no floating labels or arrows.
const trail = [
	[-59, 7],
	[-8, 7],
	[-8, 19],
	[-59, 19],
];
add(
	"trail",
	[-33.5, 13, 0.1],
	k.extrude(trail, 0, 0.2, projection),
	A.extruded(trail, 0, 0.2),
	"trail",
	"faint",
);
for (const [index, [x, y]] of [
	[-47, 12],
	[-37, 14],
	[-25, 11],
	[-16, 15],
].entries()) {
	disc(`trail.stone.${index}`, x, y, 0.8, 0.21, 0.25, "stone", "lo");
}

// Post is a real round column; its broad sign plate sits on the front face.
slab("post.foot", { x: 15, y: -17, w: 20, d: 17, r: 3 }, 0, 3, "metal", "lo");
disc("post.socket", 25, -8.5, 4, 3, 5);
disc("post.lower", 25, -8.5, 2, 8, 37);
disc("post.upper", 25, -8.5, 2, 45, 50);
const face = G.frameOf([25, -6.5, 0], [0, 1, 0], [1, 0, 0], [0, 0, 1]);
prism(
	"sign.back",
	face,
	[
		[-38, 48],
		[31, 48],
		[38, 55],
		[38, 92],
		[31, 99],
		[-38, 99],
		[-42, 94],
		[-42, 53],
	],
	0,
	2,
	"metal",
	"lo",
);
prism(
	"sign.plate",
	face,
	[
		[-38, 49],
		[31, 49],
		[37, 55],
		[37, 92],
		[31, 98],
		[-38, 98],
		[-41, 94],
		[-41, 53],
	],
	2,
	3,
	"sign",
	"hi",
);
prism(
	"sign.face",
	face,
	[
		[-34, 54],
		[29, 54],
		[32, 57],
		[32, 90],
		[29, 93],
		[-34, 93],
		[-37, 90],
		[-37, 57],
	],
	3,
	3.8,
	"face",
	"hi",
);
for (const [index, [x, z]] of [
	[-35, 56],
	[30, 56],
	[-35, 91],
	[30, 91],
].entries()) {
	const frame = G.frameOf([25 + x, -2.7, z], [0, 1, 0], [1, 0, 0], [0, 0, 1]);
	add(
		`sign.screw.${index}`,
		frame.o,
		G.disc(0, 0.5, 0.65, frame, projection),
		A.disc(frame, 0, 0.5, 0.65),
		"metal",
		"lo",
	);
}

const settled = A.settle(recorder, projection);
const ordered = [...settled.items]
	.sort((a, b) => a.key - b.key)
	.map((item) => parts.get(item.name));
const geometry = {
	width,
	height,
	projection,
	halo: k.haloOf(base, -9, 1, projection),
	number: k.sideMatrix([22.5, -2.55], 64, projection, "left"),
	parts: ordered,
};
const destination = new URL(
	"../src/components/not-found-geometry.ts",
	import.meta.url,
);
writeFileSync(
	destination,
	`// Generated by scripts/build-not-found-art.mjs with Anatomy's MIT-licensed kit.\n// Edit the generator, not path coordinates.\nimport type { Projection, SolidPaths, Tone } from './anatomy/kit';\nexport interface AnatomyPart { name: string; paths: SolidPaths; tone: Tone; material: string; line: string; dots: number[][]; }\nexport const NOT_FOUND_GEOMETRY: { width: number; height: number; projection: Projection; halo: string; number: string; parts: AnatomyPart[] } = ${JSON.stringify(geometry)};\n`,
);
console.log(
	`Anatomy wayfinder: ${ordered.length} solids, ${settled.overlaps.pairs.length} measured overlaps.`,
);
A.auditOrExit(recorder, projection);
